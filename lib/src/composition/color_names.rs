use super::ColorRgb;

/// [ColorRgb] with a human-readable name.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ColorName {
    pub name: &'static str,
    pub color: ColorRgb,
}

impl ColorName {
    /// `rgb` as `0xRRGGBB`.
    const fn hex(name: &'static str, rgb: u32) -> Self {
        Self {
            name,
            color: ColorRgb {
                r: channel(rgb, 16),
                g: channel(rgb, 8),
                b: channel(rgb, 0),
            },
        }
    }
}

/// The byte of `rgb` at `shift` as 0..=1.
const fn channel(rgb: u32, shift: u32) -> f32 {
    ((rgb >> shift) & 0xff) as f32 / 255.0
}

